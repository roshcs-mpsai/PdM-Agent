"""Who built what: the build plan's task owners and the commits on a branch (T37).

    python tools/contributions.py [--since <commit>] [--out docs/CONTRIBUTIONS.md]

Lists, per team member, the tasks the build plan (Oct 3, 2026) assigns them and the commits
attributed to them since ``--since`` (default: the first commit that is not on the R1b
detector-selection branch), from ``git log``. The page is generated; edit the owners below
when the plan changes, not the page.
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "CONTRIBUTIONS.md"

# The build plan's tracker (PdM-Agent_Build_Plan_2026-10-03, owners as confirmed at the Oct 4 sync).
OWNERS = {
    "Rosh Sreedharan": ["T1", "T3 ingest", "T4", "T5", "T6", "T7", "T12a", "T15b", "T21", "T23", "T27", "T28",
                        "T30", "T31", "T36", "T37"],
    "Ashok Reddy Buthukuri": ["T2", "T11", "T12b", "T15a", "T16", "T17", "T20", "T22", "T24", "T26", "T29"],
    "Gayatri Suresh Chaudhari": ["T3 database", "T8", "T13", "T14", "T18", "T19", "T25", "T32", "T33", "T34",
                                 "T35", "T38"],
}
TASK = re.compile(r"\bT\d+[ab]?\b")


def task_order(task: str) -> tuple:
    """T2 before T12a before T12b before T15a: by number, then the letter."""
    return int(re.sub(r"\D", "", task)), task[-1] if task[-1].isalpha() else ""


def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, check=True).stdout


def default_since() -> str:
    for ref in ("origin/r1b-detector-selection", "r1b-detector-selection"):
        try:
            return git("merge-base", "HEAD", ref).strip()
        except subprocess.CalledProcessError:
            continue
    return git("rev-list", "--max-parents=0", "HEAD").split()[0]


def commits(since: str) -> list[dict]:
    out = []
    for line in git("log", "--reverse", "--format=%h%x1f%an%x1f%ad%x1f%s", "--date=short",
                    f"{since}..HEAD").splitlines():
        h, author, date, subject = line.split("\x1f")
        out.append({"hash": h, "author": author, "date": date, "subject": subject,
                    "tasks": sorted(set(TASK.findall(subject)), key=task_order)})
    return out


def page(since: str, rows: list[dict]) -> str:
    by_author = defaultdict(list)
    for r in rows:
        by_author[r["author"]].append(r)
    head = git("rev-parse", "--short", "HEAD").strip()
    lines = ["# Contributions", "",
             f"Commits on this branch from `{since[:7]}` to `{head}`, by author, with the tasks the build plan "
             "(Oct 3, 2026) assigns each team member. Every commit carries a Co-Authored-By line for Claude, "
             "which drafted the code. Changes reach main by pull request with green CI (README, working "
             "agreements). Generated by `python tools/contributions.py`.", "",
             "| Team member | Tasks in the build plan | Commits |", "|---|---|---|"]
    for person, tasks in OWNERS.items():
        lines.append(f"| {person} | {', '.join(tasks)} | {len(by_author.get(person, []))} |")
    others = sorted(set(by_author) - set(OWNERS))
    for person in others:
        lines.append(f"| {person} | (not in the plan) | {len(by_author[person])} |")
    for person in list(OWNERS) + others:
        if not by_author.get(person):
            continue
        lines += ["", f"## {person}", "", "| Commit | Date | Tasks | What |", "|---|---|---|---|"]
        for r in by_author[person]:
            subject = r["subject"].replace("|", "/")
            lines.append(f"| `{r['hash']}` | {r['date']} | {', '.join(r['tasks']) or '-'} | {subject} |")
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--since", default=None, help="the commit before the first one listed")
    p.add_argument("--out", default=str(OUT))
    args = p.parse_args(argv)
    since = args.since or default_since()
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(page(since, commits(since)))
    print(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
