"""The PdM-Agent store: one schema, two engines (T3; FRD section 8, ESR-02, HIL-05).

Every service that keeps records -- ingest, detector, prognostics, gate, the
MCP tool server, the agent, the API, the connector -- writes them through this
module. The schema is declared once, in ``SCHEMA`` below, and rendered for:

* PostgreSQL with TimescaleDB, the deployed store (``db/init/001_schema.sql``,
  generated by ``python -m pdm_common.store --ddl postgres``; telemetry, windows,
  scores and prognoses become hypertables when the extension is present);
* SQLite, for tests, notebooks and the single-process pipeline
  (``sqlite:///path`` or ``sqlite://`` for memory).

Insert-only tables refuse UPDATE and DELETE in the database itself, through a
trigger, so an audit record cannot be changed by application code (ESR-02,
HIL-05): incident_events, gate_log, status_log, tool_results, agent_traces,
briefs, decisions, study_sessions and promotions. Signals and features live in
JSON columns, so the schema names no asset channel (CFG-03).

Rows come back as plain dicts: timestamps as ISO 8601 UTC strings with ``Z``,
JSON columns parsed, booleans as bool. Writes take the same forms (datetimes
and dicts are converted).
"""
