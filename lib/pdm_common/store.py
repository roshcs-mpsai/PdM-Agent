INSERT_ONLY = [name for name, t in SCHEMA.items() if t.get("insert_only")]
JSON_COLUMNS = {name: {c for c, k in t["columns"] if k == "json"} for name, t in SCHEMA.items()}
TS_COLUMNS = {name: {c for c, k in t["columns"] if k == "ts"} for name, t in SCHEMA.items()}
BOOL_COLUMNS = {name: {c for c, k in t["columns"] if k == "bool"} for name, t in SCHEMA.items()}

SQLITE_TS = "%Y-%m-%dT%H:%M:%S.%fZ"
PG_TYPES = {"text": "TEXT", "int": "BIGINT", "real": "DOUBLE PRECISION", "bool": "BOOLEAN", "ts": "TIMESTAMPTZ",
            "json": "JSONB", "serial": "BIGSERIAL"}
SQLITE_TYPES = {"text": "TEXT", "int": "INTEGER", "real": "REAL", "bool": "INTEGER", "ts": "TEXT", "json": "TEXT",
                "serial": "INTEGER"}


def ddl(dialect: str) -> str:
    """CREATE statements, insert-only triggers and (Postgres) hypertables."""
    out = []
    if dialect == "postgres":
        out.append("-- Generated by: python -m pdm_common.store --ddl postgres > db/init/001_schema.sql\n"
                   "-- The schema is declared in lib/pdm_common/store.py; edit it there and regenerate.\n"
                   "DO $$ BEGIN CREATE EXTENSION IF NOT EXISTS timescaledb;\n"
                   "EXCEPTION WHEN OTHERS THEN RAISE NOTICE 'timescaledb not available: plain tables'; END $$;\n")
    for name, t in SCHEMA.items():
        cols = []
        for col, kind in t["columns"]:
            if dialect == "sqlite" and kind == "serial":
                cols.append(f"  {col} INTEGER PRIMARY KEY AUTOINCREMENT")
            else:
                types = PG_TYPES if dialect == "postgres" else SQLITE_TYPES
                cols.append(f"  {col} {types[kind]}")
        if not (dialect == "sqlite" and any(k == "serial" for _, k in t["columns"])):
            cols.append(f"  PRIMARY KEY ({', '.join(t['pk'])})")
        for unique in t.get("unique", []):
            cols.append(f"  UNIQUE ({', '.join(unique)})")
        out.append(f"-- {t['doc']}\nCREATE TABLE IF NOT EXISTS {name} (\n" + ",\n".join(cols) + "\n);")
    out.append(_indexes())
    if dialect == "postgres":
        out.append("CREATE OR REPLACE FUNCTION forbid_change() RETURNS trigger AS $$\n"
                   "BEGIN\n  RAISE EXCEPTION '% is insert-only', TG_TABLE_NAME;\nEND;\n$$ LANGUAGE plpgsql;")
        for name in INSERT_ONLY:
            out.append(f"DROP TRIGGER IF EXISTS {name}_insert_only ON {name};\n"
                       f"CREATE TRIGGER {name}_insert_only BEFORE UPDATE OR DELETE ON {name}\n"
                       f"  FOR EACH ROW EXECUTE FUNCTION forbid_change();")
        hyper = [f"    PERFORM create_hypertable('{n}', '{t['hypertable']}', if_not_exists => TRUE);"
                 for n, t in SCHEMA.items() if t.get("hypertable")]
        out.append("DO $$ BEGIN\n  IF EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'timescaledb') THEN\n"
                   + "\n".join(hyper) + "\n  END IF;\nEND $$;")
    else:
        for name in INSERT_ONLY:
            for op in ("UPDATE", "DELETE"):
                out.append(f"CREATE TRIGGER IF NOT EXISTS {name}_no_{op.lower()} BEFORE {op} ON {name}\n"
                           f"BEGIN SELECT RAISE(ABORT, '{name} is insert-only'); END;")
    return "\n\n".join(out) + "\n"


def _indexes() -> str:
    idx = [("tool_results", ["incident_id"]), ("briefs", ["incident_id"]), ("decisions", ["incident_id"]),
           ("incident_events", ["incident_id"]), ("work_orders", ["status"]), ("incidents", ["asset_id", "state"]),
           ("gate_log", ["asset_id", "at"]), ("study_sessions", ["session_id"])]
    return "\n".join(f"CREATE INDEX IF NOT EXISTS {t}_{'_'.join(c)}_idx ON {t} ({', '.join(c)});" for t, c in idx)


# --- values in and out ---------------------------------------------------------------------------

def _to_db(table: str, column: str, value, dialect: str):
    if value is None:
        return None
    if column in JSON_COLUMNS[table]:
        return json.dumps(value, sort_keys=True, default=_json_default)
    if column in TS_COLUMNS[table]:
        moment = to_utc(value) if not isinstance(value, dt.datetime) or value.tzinfo is None else value
        # SQLite compares text: a fixed width (microseconds always present) keeps the order right
        return moment.astimezone(dt.timezone.utc).strftime(SQLITE_TS) if dialect == "sqlite" else moment
    if column in BOOL_COLUMNS[table]:
        return int(bool(value)) if dialect == "sqlite" else bool(value)
    return value


def _json_default(value):
    if isinstance(value, dt.datetime):
        return iso_utc(to_utc(value))
    if hasattr(value, "item"):           # numpy scalars
        return value.item()
    if hasattr(value, "tolist"):
        return value.tolist()
    raise TypeError(f"{type(value).__name__} is not JSON serializable")


def _from_db(table: str | None, row: dict, dialect: str = "sqlite") -> dict:
    if table is None:
        return dict(row)
    out = {}
    for col, value in row.items():
        if value is not None and col in JSON_COLUMNS.get(table, ()):
            # psycopg returns JSONB already parsed; SQLite keeps the text
            value = json.loads(value) if dialect == "sqlite" else value
        elif value is not None and col in TS_COLUMNS.get(table, ()):
            value = iso_utc(to_utc(value)) if not isinstance(value, dt.datetime) else iso_utc(value.astimezone(dt.timezone.utc))
        elif value is not None and col in BOOL_COLUMNS.get(table, ()):
            value = bool(value)
        out[col] = value
    return out


# --- the store ----------------------------------------------------------------------------------

class StoreError(RuntimeError):
    pass


class Store:
    """A connection to the store. ``Store('sqlite:///runs/pdm.db')``,
    ``Store('sqlite://')`` (memory) or ``Store('postgresql://pdm:...@localhost/pdm')``."""

    def __init__(self, url: str):
        self.url = url
        self._lock = threading.RLock()
        if url.startswith("sqlite://"):
            self.dialect = "sqlite"
            path = url[len("sqlite://"):].lstrip("/") if url != "sqlite://" else ":memory:"
            if url.startswith("sqlite:////"):
                path = "/" + url[len("sqlite:////"):]
            if path != ":memory:":
                Path(path).parent.mkdir(parents=True, exist_ok=True)
            self.conn = sqlite3.connect(path, check_same_thread=False, isolation_level=None)
            self.conn.row_factory = sqlite3.Row
            self.conn.execute("PRAGMA foreign_keys = ON")
            if path != ":memory:":
                self.conn.execute("PRAGMA journal_mode = WAL")
        elif url.startswith(("postgresql://", "postgres://")):
            self.dialect = "postgres"
            import psycopg
            from psycopg.rows import dict_row
            self.conn = psycopg.connect(url, autocommit=True, row_factory=dict_row)
        else:
            raise StoreError(f"unknown store URL {url!r}: use sqlite:///path or postgresql://...")
        self._depth = 0

    # -- plumbing --
    def init_schema(self) -> None:
        """Create every table, index and trigger if it does not exist."""
        with self._lock:
            if self.dialect == "sqlite":
                self.conn.executescript(ddl("sqlite"))
            else:
                self.conn.execute(ddl("postgres"))

    def _sql(self, sql: str) -> str:
        return sql.replace("?", "%s") if self.dialect == "postgres" else sql

    @contextmanager
    def transaction(self):
        """All writes inside commit together or not at all (nesting joins the outer one)."""
        with self._lock:
            if self._depth:
                self._depth += 1
                try:
                    yield self
                finally:
                    self._depth -= 1
                return
            self._depth = 1
            try:
                if self.dialect == "postgres":
                    with self.conn.transaction():
                        yield self
                else:
                    self.conn.execute("BEGIN")
                    try:
                        yield self
                    except BaseException:
                        self.conn.execute("ROLLBACK")
                        raise
                    self.conn.execute("COMMIT")
            finally:
                self._depth = 0

    def execute(self, sql: str, params: Iterable = ()) -> int:
        """Run one statement; returns the number of rows it changed."""
        with self._lock:
            cur = self.conn.execute(self._sql(sql), tuple(params))
            return cur.rowcount if cur.rowcount is not None else -1

    def query(self, sql: str, params: Iterable = (), table: str | None = None) -> list[dict]:
        with self._lock:
            cur = self.conn.execute(self._sql(sql), tuple(params))
            rows = cur.fetchall()
        return [_from_db(table, dict(r), self.dialect) for r in rows]

    def one(self, sql: str, params: Iterable = (), table: str | None = None) -> dict | None:
        rows = self.query(sql, params, table)
        return rows[0] if rows else None

    def close(self) -> None:
        with self._lock:
            self.conn.close()

    # -- generic writes --
    def insert(self, table: str, row: dict, *, ignore_conflict: bool = False) -> None:
        if table not in SCHEMA:
            raise StoreError(f"unknown table {table}")
        cols = [c for c, _ in SCHEMA[table]["columns"] if c in row]
        values = [_to_db(table, c, row[c], self.dialect) for c in cols]
        conflict = " ON CONFLICT DO NOTHING" if ignore_conflict else ""
        self.execute(f"INSERT INTO {table} ({', '.join(cols)}) VALUES ({', '.join('?' * len(cols))}){conflict}",
                     values)

    def insert_many(self, table: str, rows: list[dict], *, ignore_conflict: bool = True) -> int:
        if not rows:
            return 0
        cols = [c for c, _ in SCHEMA[table]["columns"] if c in rows[0]]
        conflict = " ON CONFLICT DO NOTHING" if ignore_conflict else ""
        sql = self._sql(f"INSERT INTO {table} ({', '.join(cols)}) VALUES ({', '.join('?' * len(cols))}){conflict}")
        data = [tuple(_to_db(table, c, r.get(c), self.dialect) for c in cols) for r in rows]
        with self.transaction():
            if self.dialect == "sqlite":
                self.conn.executemany(sql, data)
            else:
                with self.conn.cursor() as cur:
                    cur.executemany(sql, data)
        return len(rows)

    def update(self, table: str, key: dict, values: dict) -> int:
        """For the tables whose rows change: incidents (via pdm_common.incidents) and
        work_orders. ``key`` may hold any columns, so an update can be conditional
        (compare and set); returns the number of rows changed."""
        if table in INSERT_ONLY:
            raise StoreError(f"{table} is insert-only")
        sets = ", ".join(f"{c} = ?" for c in values)
        where = " AND ".join(f"{c} = ?" for c in key)
        params = [_to_db(table, c, v, self.dialect) for c, v in values.items()] + \
                 [_to_db(table, c, v, self.dialect) for c, v in key.items()]
        return self.execute(f"UPDATE {table} SET {sets} WHERE {where}", params)

    def select(self, table: str, where: dict | None = None, order: str | None = None, limit: int | None = None,
               columns: str = "*") -> list[dict]:
        where = where or {}
        clause = (" WHERE " + " AND ".join(f"{c} = ?" for c in where)) if where else ""
        tail = (f" ORDER BY {order}" if order else "") + (f" LIMIT {int(limit)}" if limit else "")
        params = [_to_db(table, c, v, self.dialect) for c, v in where.items()]
        return self.query(f"SELECT {columns} FROM {table}{clause}{tail}", params, table)

    def count(self, table: str, where: dict | None = None) -> int:
        row = self.select(table, where, columns="COUNT(*) AS n")[0]
        return int(row["n"])

    # -- time-range reads (as-of reads build on these) --
    def between(self, table: str, column: str, asset_id: str, start, end, *, end_inclusive: bool = True,
                order: str | None = None, limit: int | None = None) -> list[dict]:
        op = "<=" if end_inclusive else "<"
        sql = (f"SELECT * FROM {table} WHERE asset_id = ? AND {column} >= ? AND {column} {op} ?"
               f" ORDER BY {order or column}" + (f" LIMIT {int(limit)}" if limit else ""))
        return self.query(sql, [asset_id, _to_db(table, column, start, self.dialect),
                                _to_db(table, column, end, self.dialect)], table)

    def latest(self, table: str, column: str, asset_id: str, before=None) -> dict | None:
        if before is None:
            return self.one(f"SELECT * FROM {table} WHERE asset_id = ? ORDER BY {column} DESC LIMIT 1",
                            [asset_id], table)
        return self.one(f"SELECT * FROM {table} WHERE asset_id = ? AND {column} <= ? ORDER BY {column} DESC LIMIT 1",
                        [asset_id, _to_db(table, column, before, self.dialect)], table)


def open_store(url: str | None = None, *, init: bool = True) -> Store:
    """The store at ``url`` or $PDM_STORE (default: sqlite:///runs/pdm.db), schema created."""
    import os
    store = Store(url or os.environ.get("PDM_STORE", "sqlite:///runs/pdm.db"))
    if init:
        store.init_schema()
    return store


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description="Print the store's DDL")
    p.add_argument("--ddl", choices=["postgres", "sqlite"], required=True)
    args = p.parse_args(argv)
    sys.stdout.write(ddl(args.ddl))
    return 0


if __name__ == "__main__":
    sys.exit(main())
